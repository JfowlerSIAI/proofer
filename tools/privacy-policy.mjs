#!/usr/bin/env node
// One authored policy template; its readable Markdown is generated and checked.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export function renderPolicy(maintainerSource, template) {
  const contact = vm.runInNewContext(`${maintainerSource}\nPROOFER_MAINTAINER`, {}, { timeout: 1000 });
  if (!contact || typeof contact.name !== "string" || !contact.name.trim() ||
      typeof contact.email !== "string" || !/^[^\s<>@]+@[^\s<>@]+\.[^\s<>@]+$/.test(contact.email)) {
    throw new Error("maintainer.js must provide a name and email address.");
  }
  const escape = (value) => value.replace(/[\\`*_{}\[\]<>]/g, "\\$&");
  return "<!-- Generated by tools/privacy-policy.mjs from privacy-policy.template.md and maintainer.js. -->\n" +
    template.replaceAll("{{maintainerName}}", escape(contact.name)).replaceAll("{{maintainerEmail}}", contact.email);
}

export function policyForCheckout(checkout = root) {
  return renderPolicy(fs.readFileSync(path.join(checkout, "maintainer.js"), "utf8"),
    fs.readFileSync(path.join(checkout, "docs/privacy-policy.template.md"), "utf8"));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length && args[0] !== "--check")) {
    console.error("Usage: node tools/privacy-policy.mjs [--check]");
    process.exit(2);
  }
  const expected = policyForCheckout();
  const destination = path.join(root, "docs/privacy-policy.md");
  if (args[0] === "--check") {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== expected) {
      console.error("Privacy policy is stale. Run node tools/privacy-policy.mjs.");
      process.exit(1);
    }
    console.log("Privacy policy matches its template and maintainer setting.");
  } else {
    fs.writeFileSync(destination, expected);
    console.log("Updated docs/privacy-policy.md.");
  }
}
