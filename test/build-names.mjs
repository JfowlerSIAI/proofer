#!/usr/bin/env node
// Builds data/names-en.txt -- the cased proper-noun list the sentence guards
// consult for names -- from the SCOWL-derived Debian word list that
// data/words-en.txt itself came from, and writes its integrity constants into
// background.js. Same contract as build-confusables.mjs: the file is a LICENCE
// (it lets a non-word be corrected to a cased name), so the loader fails closed
// on count and digest, and the constants are written by this builder rather
// than by hand.
//
//   node build-names.mjs            # rebuild data/names-en.txt + patch background.js
//   node build-names.mjs --check    # build in memory; exit 1 on drift in the
//                                   # artifact OR in background.js's constants
//
// SOURCE: /usr/share/dict/american-english from `wamerican 2020.12.07-2`
// (SCOWL 2020.12.07, American, size 50 -- the same package and size the word
// list was taken from, so the two files describe one vocabulary). Not vendored:
// the source is 985 KB and its digest is recorded in the header instead, so a
// rebuild on a machine with a different package version is visible as a
// header change before it is visible as a licence change.
//
// SELECTION, and what is deliberately left out:
//   in:  Title-case words (`Florida`, `Buddhist`, `Stephanie`), mixed-case
//        brands (`GitHub`, `iPhone`, `McDonald`), all-caps initialisms of three
//        letters or more (`NASA`, `HTML`, `URL`), and cased entries carrying an
//        apostrophe or hyphen (`O'Brien`, `Jean-Claude`) -- ASCII only.
//   out: possessives (`Florida's`; a possessive is derived at lookup time),
//        single letters and two-letter initialisms (`US`, `IT`, `SO` -- an
//        initialism this short is the documented `SO means significant other`
//        ambiguity, and the licence must not be able to reach it), the pronoun
//        contractions (`I'd`, `I'll`, `I'm`, `I've`), and accented entries
//        (`Zurich` is in; `Zürich` is not -- the guards' typography check
//        already refuses an accent the model dropped, and asciify() does not
//        touch accents, so nothing downstream could match them).
import { readFileSync, writeFileSync, existsSync } from "fs";
import { createHash } from "crypto";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "data", "names-en.txt");
const BACKGROUND = join(HERE, "..", "background.js");
const SOURCE = process.env.PROOFER_NAMES_SOURCE || "/usr/share/dict/american-english";

const sha256 = (s) => createHash("sha256").update(s).digest("hex");

export function selectNames(sourceText) {
  const out = new Set();
  for (const raw of sourceText.split("\n")) {
    const w = raw.replace(/\r$/, "").trim();
    if (!w || !/^[A-Z]/.test(w)) continue;
    if (/[^\x21-\x7e]/.test(w)) continue;                 // ASCII only
    if (/'s$/.test(w)) continue;                          // possessives derived at lookup
    if (/^I'(?:d|ll|m|ve)$/.test(w)) continue;            // pronoun contractions
    if (!/^[A-Z][A-Za-z]*(?:['-][A-Za-z]+)*$/.test(w)) continue;
    if (/^[A-Z]+$/.test(w) && w.length < 3) continue;     // single letters, two-letter initialisms
    if (w.length < 2) continue;
    out.add(w);
  }
  return [...out].sort();
}

export function render(names, sourceDigest) {
  const header = [
    "# Cased proper nouns, brands and initialisms for Proofer's sentence-mode guards.",
    "#",
    "# GENERATED by test/build-names.mjs -- do not edit by hand. The loader in",
    "# background.js verifies this file's entry count and SHA-256 against constants",
    "# the builder writes into background.js, and publishes NOTHING if either",
    "# disagrees: a hand edit here does not add a name, it revokes all of them.",
    "#",
    "# Each line is one cased entry. It licenses the model to correct a NON-WORD",
    "# to this exact casing at a small edit distance when no dictionary word sits",
    "# as close -- `FLordia` -> `Florida`, `budhist` -> `Buddhist`, `github` ->",
    "# `GitHub` -- which isRespelling()/protected-token would otherwise refuse",
    "# because the word list holds lowercase common words only. It never licenses",
    "# changing a listed name into another (`Alice` -> `Alicia`), and a common word",
    "# at the same distance always wins (`Whles` -> `Wales` stays refused: `whales`).",
    "#",
    "# Source: SCOWL 2020.12.07 as packaged in Debian/Ubuntu `wamerican 2020.12.07-2`",
    `# (/usr/share/dict/american-english, sha256 ${sourceDigest}), capitalised`,
    "# entries selected as build-names.mjs documents. SCOWL's copyright and",
    "# permission notice is in data/COPYRIGHT.SCOWL-2020.12.07 and applies here.",
    "",
  ];
  return header.join("\n") + names.join("\n") + "\n";
}

export function payloadDigest(names) {
  return sha256(names.join("\n") + "\n");
}

export function patchBackground(src, count, digest) {
  const next = src
    .replace(/(const NAMES_COUNT = )\d+(;)/, `$1${count}$2`)
    .replace(/(const NAMES_SHA256 = ")[0-9a-f]*(";)/, `$1${digest}$2`);
  if (!/const NAMES_COUNT = \d+;/.test(next) || !/const NAMES_SHA256 = "[0-9a-f]{64}";/.test(next)) {
    throw new Error("background.js has no NAMES_COUNT / NAMES_SHA256 to patch");
  }
  return next;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!existsSync(SOURCE)) {
    console.error(`source word list not found: ${SOURCE} (install wamerican, or set PROOFER_NAMES_SOURCE)`);
    process.exit(2);
  }
  const sourceText = readFileSync(SOURCE, "utf8");
  const names = selectNames(sourceText);
  const digest = payloadDigest(names);
  const text = render(names, sha256(sourceText));
  const bg = readFileSync(BACKGROUND, "utf8");
  const patched = patchBackground(bg, names.length, digest);
  if (process.argv.includes("--check")) {
    const problems = [];
    if (!existsSync(OUT)) problems.push(`${OUT} is missing`);
    else {
      const have = readFileSync(OUT, "utf8").split("\n").map((l) => l.replace(/\r$/, "").trim()).filter((l) => l && !l.startsWith("#"));
      if (have.length !== names.length || payloadDigest(have) !== digest) problems.push("data/names-en.txt does not match a rebuild from the source");
    }
    if (patched !== bg) problems.push("background.js NAMES_COUNT / NAMES_SHA256 do not match the artifact");
    if (problems.length) { for (const p of problems) console.error(p); process.exit(1); }
    console.log(`data/names-en.txt and background.js's integrity constants are up to date.\n  entries ${names.length}  sha256 ${digest}`);
  } else {
    writeFileSync(OUT, text);
    if (patched !== bg) writeFileSync(BACKGROUND, patched);
    console.log(`wrote ${names.length} names to data/names-en.txt; sha256 ${digest}`);
  }
}
